#!/usr/bin/env python3
"""Run every experiment and regenerate every figure, data file and caption.

    python run_all.py                      # all figures -> output/
    python run_all.py --only fig07 fig09   # a subset
    python run_all.py --verify             # also run the verification suite
    python run_all.py --verify --quick     # faster verification (smaller circuits)

Outputs
    output/figures/<stem>.pdf|png   figures, named as in the paper's LaTeX source
    output/data/<figure id>.csv     every plotted value
    output/captions.tex             LaTeX captions (numbers taken from the computed data)
    output/verification.txt         verification report (with --verify)
"""

import argparse
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from figures import ALL, BY_ID  # noqa: E402
from figures.common import Saver, evaluate, write_csv  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="output", help="output directory (default: output)")
    ap.add_argument("--only", nargs="+", metavar="FIG", choices=sorted(BY_ID), help="figure ids to run")
    ap.add_argument("--verify", action="store_true", help="run the verification suite")
    ap.add_argument("--quick", action="store_true", help="smaller verification (skips the largest brute-force cases)")
    args = ap.parse_args()

    mods = [BY_ID[i] for i in args.only] if args.only else ALL
    saver = Saver(os.path.join(args.out, "figures"))
    rows_by_fig, captions = {}, []
    for mod in mods:
        t0 = time.time()
        rows = [evaluate(cfg) for cfg in mod.configs()]
        rows_by_fig[mod.ID] = rows
        write_csv(os.path.join(args.out, "data", f"{mod.ID}.csv"), rows)
        mod.plot(rows, saver)
        captions.append(f"% {'-' * 70}\n% {mod.ID}: {mod.TITLE}\n{mod.caption(rows)}")
        print(f"{mod.ID}  {mod.TITLE:<78s} {len(rows):3d} points  {time.time() - t0:6.1f} s", flush=True)

    with open(os.path.join(args.out, "captions.tex"), "w") as f:
        f.write("% Captions generated by run_all.py; all quoted numbers come from output/data/*.csv.\n")
        f.write("% Mismatch costs are in bits (base-2 logarithms).\n\n")
        f.write("\n\n".join(captions) + "\n")
    print(f"\nwrote {len(saver.written)} figure files, {len(mods)} CSVs and captions.tex to {args.out}/")

    if args.verify:
        sys.exit(0 if run_verification(mods, rows_by_fig, args) else 1)


def run_verification(mods, rows_by_fig, args):
    from mmc.verify import check_equations, check_figure_points
    lines, ok = [], True
    t0 = time.time()
    lines.append("1. Equations vs brute force (Eq. B5 on the full joint distribution; random priors, input")
    lines.append("   distributions, topological orders, and random q_pa / q_rest / q_nin):")
    for name, err in check_equations(quick=args.quick):
        good = err < 1e-9
        ok &= good
        lines.append(f"   {'PASS' if good else 'FAIL'}  {name:<48s} max error {err:.1e} bits")
    lines.append("\n2. Plotted points recomputed by brute force (Eq. B5), all points small enough:")
    pts = check_figure_points(mods, rows_by_fig, max_nodes=16 if args.quick else 22)
    worst = 0.0
    for fig_id, desc, plotted, bf in pts:
        err = abs(plotted - bf)
        worst = max(worst, err)
        lines.append(f"   {'PASS' if err < 1e-8 else 'FAIL'}  {fig_id}  {desc:<44s} plotted {plotted:12.6f}  brute force {bf:12.6f}")
    ok &= worst < 1e-8
    lines.append(f"\n   {len(pts)} points checked, max error {worst:.1e} bits")
    lines.append(f"\n{'ALL CHECKS PASSED' if ok else 'SOME CHECKS FAILED'}  ({time.time() - t0:.0f} s)")
    report = "\n".join(lines)
    print("\n" + report)
    with open(os.path.join(args.out, "verification.txt"), "w") as f:
        f.write(report + "\n")
    return ok


if __name__ == "__main__":
    main()
